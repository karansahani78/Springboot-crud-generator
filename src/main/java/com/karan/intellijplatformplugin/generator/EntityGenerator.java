package com.karan.intellijplatformplugin.generator;

import com.intellij.ide.highlighter.JavaFileType;
import com.intellij.openapi.project.Project;
import com.intellij.psi.PsiClass;
import com.intellij.psi.PsiDirectory;
import com.intellij.psi.PsiFile;
import com.intellij.psi.PsiJavaFile;
import com.intellij.psi.PsiFileFactory;
import com.intellij.psi.util.PsiUtilCore;
import com.karan.intellijplatformplugin.model.ClassMeta;
import com.karan.intellijplatformplugin.model.GenerationOptions;
import com.karan.intellijplatformplugin.prompt.EntityDefinition;
import com.karan.intellijplatformplugin.prompt.FieldTypeResolver;
import com.karan.intellijplatformplugin.prompt.PromptFieldDefinition;
import com.karan.intellijplatformplugin.util.PsiDirectoryUtil;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Generates the JPA entity for prompt mode.
 *
 * <p>The resulting PSI class is validated and then converted with
 * {@link PsiDirectoryUtil#toClassMeta(PsiClass)} so prompt mode enters the same
 * metadata pipeline as the original entity-based workflow.
 */
public final class EntityGenerator {

    private EntityGenerator() {
        throw new AssertionError("Utility class cannot be instantiated");
    }

    /** Result of creating the entity file in the IntelliJ project model. */
    public static final class Result {
        private final PsiClass psiClass;
        private final ClassMeta classMeta;

        public Result(PsiClass psiClass, ClassMeta classMeta) {
            this.psiClass = psiClass;
            this.classMeta = classMeta;
        }

        public PsiClass getPsiClass() { return psiClass; }
        public ClassMeta getClassMeta() { return classMeta; }
    }

    /**
     * Pure source builder — used by the generator and by unit tests.
     *
     * @param namespace {@code jakarta} or {@code javax}
     */
    public static String buildEntitySource(
            EntityDefinition definition,
            GenerationOptions options,
            String namespace,
            String basePackage
    ) {
        if (definition == null) throw new IllegalArgumentException("Entity definition cannot be null");
        PromptFieldDefinition idField = definition.getIdField();
        if (idField == null) throw new IllegalArgumentException("Exactly one primary key is required");

        String ns = "javax".equalsIgnoreCase(namespace) ? "javax" : "jakarta";
        String packageName = definition.getPackageName() == null || definition.getPackageName().isBlank()
                ? basePackage + ".entity"
                : definition.getPackageName();
        boolean validation = options != null && options.isGenerateValidation();

        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(packageName).append(";\n\n");

        Set<String> imports = new LinkedHashSet<>();
        imports.add(ns + ".persistence.Column");
        imports.add(ns + ".persistence.Entity");
        imports.add(ns + ".persistence.GeneratedValue");
        imports.add(ns + ".persistence.GenerationType");
        imports.add(ns + ".persistence.Id");
        if (definition.isTableAnnotation()) imports.add(ns + ".persistence.Table");

        if (validation) {
            if (hasConstraint(definition, "required", "textual")) imports.add("jakarta.validation.constraints.NotBlank");
            if (hasConstraint(definition, "required", "nonTextual")) imports.add("jakarta.validation.constraints.NotNull");
            if (definition.getFields().stream().anyMatch(PromptFieldDefinition::isEmail))
                imports.add("jakarta.validation.constraints.Email");
            if (definition.getFields().stream().anyMatch(f -> f.getSize() != null))
                imports.add("jakarta.validation.constraints.Size");
            if (definition.getFields().stream().anyMatch(f -> f.getMin() != null))
                imports.add("jakarta.validation.constraints.Min");
            if (definition.getFields().stream().anyMatch(f -> f.getMax() != null))
                imports.add("jakarta.validation.constraints.Max");
        }
        imports.addAll(FieldTypeResolver.importsFor(definition.getFields()));

        List<String> sortedImports = new ArrayList<>(imports);
        sortedImports.sort((a, b) -> {
            boolean aValidation = a.startsWith("jakarta.validation");
            boolean bValidation = b.startsWith("jakarta.validation");
            if (aValidation != bValidation) return aValidation ? 1 : -1;
            return a.compareTo(b);
        });
        for (String imp : sortedImports) {
            sb.append("import ").append(imp).append(";\n");
        }
        sb.append('\n');

        sb.append("/**\n * Generated by AutoSpring from a developer prompt.\n */\n");
        sb.append("@Entity\n");
        if (definition.isTableAnnotation()) {
            sb.append("@Table(name = \"").append(definition.getTableName()).append("\")\n");
        }
        sb.append("public class ").append(definition.getClassName()).append(" {\n\n");

        // Primary key first.
        appendField(sb, idField, validation, true);
        for (PromptFieldDefinition field : definition.getNonIdFields()) {
            appendField(sb, field, validation, false);
        }

        sb.append("    public ").append(definition.getClassName()).append("() {\n    }\n\n");

        for (PromptFieldDefinition field : definition.getFields()) {
            String capitalized = capitalize(field.getName());
            String getterPrefix = "boolean".equals(field.getJavaType()) ? "is" : "get";
            sb.append("    public ").append(field.getJavaType()).append(' ')
                    .append(getterPrefix).append(capitalized).append("() {\n")
                    .append("        return this.").append(field.getName()).append(";\n")
                    .append("    }\n\n");
            sb.append("    public void set").append(capitalized).append('(')
                    .append(field.getJavaType()).append(' ').append(field.getName()).append(") {\n")
                    .append("        this.").append(field.getName()).append(" = ").append(field.getName()).append(";\n")
                    .append("    }\n\n");
        }

        sb.append("}\n");
        return sb.toString();
    }

    /**
     * Creates the entity Java file using IntelliJ PSI APIs and returns its
     * parsed {@link ClassMeta}. Must be called inside a WriteCommandAction.
     */
    public static Result generate(
            Project project,
            PsiDirectory sourceRoot,
            EntityDefinition definition,
            GenerationOptions options,
            String namespace,
            String basePackage
    ) {
        if (project == null || sourceRoot == null || definition == null) {
            throw new IllegalArgumentException("Project, source root and entity definition are required");
        }

        String packageName = definition.getPackageName() == null || definition.getPackageName().isBlank()
                ? basePackage + ".entity"
                : definition.getPackageName();
        PsiDirectory targetDir = PsiDirectoryUtil.createPackageDirs(sourceRoot, packageName);
        String fileName = definition.getClassName() + ".java";

        PsiFile existing = targetDir.findFile(fileName);
        if (existing != null) {
            throw new IllegalStateException("Entity file already exists: " + fileName + " in " + packageName);
        }

        String code = buildEntitySource(definition, options, namespace, basePackage);
        PsiFile file = PsiFileFactory.getInstance(project)
                .createFileFromText(fileName, JavaFileType.INSTANCE, code);
        PsiElementAdded added = addFile(targetDir, file);

        if (!(added.file instanceof PsiJavaFile javaFile) || javaFile.getClasses().length == 0) {
            throw new IllegalStateException("Generated entity could not be parsed: " + fileName);
        }

        PsiClass psiClass = javaFile.getClasses()[0];
        if (PsiUtilCore.hasErrorElementChild(psiClass)) {
            throw new IllegalStateException("Generated entity has PSI errors: " + fileName);
        }

        ClassMeta meta = PsiDirectoryUtil.toClassMeta(psiClass);
        return new Result(psiClass, meta);
    }

    /** Tiny wrapper so the added PSI element is explicit in the code. */
    private static PsiElementAdded addFile(PsiDirectory directory, PsiFile file) {
        directory.add(file);
        return new PsiElementAdded(file);
    }

    private record PsiElementAdded(PsiFile file) {}

    private static void appendField(
            StringBuilder sb,
            PromptFieldDefinition field,
            boolean validation,
            boolean primaryKey
    ) {
        StringBuilder annotations = new StringBuilder();

        if (primaryKey) {
            annotations.append("    @Id\n");
            if (field.isGenerated()) {
                annotations.append("    @GeneratedValue(strategy = GenerationType.IDENTITY)\n");
            }
        }

        List<String> columnAttributes = new ArrayList<>();
        if (field.isRequired() || primaryKey) columnAttributes.add("nullable = false");
        if (field.isUnique()) columnAttributes.add("unique = true");
        if (!columnAttributes.isEmpty()) {
            annotations.append("    @Column(").append(String.join(", ", columnAttributes)).append(")\n");
        }

        if (validation) {
            if (field.isEmail()) annotations.append("    @Email\n");
            if (field.isRequired()) {
                annotations.append(FieldTypeResolver.isTextual(field.getJavaType())
                        ? "    @NotBlank\n" : "    @NotNull\n");
            }
            if (field.getSize() != null && FieldTypeResolver.isTextual(field.getJavaType())) {
                annotations.append("    @Size(max = ").append(field.getSize()).append(")\n");
            }
            if (field.getMin() != null && FieldTypeResolver.isNumeric(field.getJavaType())) {
                annotations.append("    @Min(").append(field.getMin()).append(")\n");
            }
            if (field.getMax() != null && FieldTypeResolver.isNumeric(field.getJavaType())) {
                annotations.append("    @Max(").append(field.getMax()).append(")\n");
            }
        }

        sb.append(annotations);
        sb.append("    private ").append(field.getJavaType()).append(' ')
                .append(field.getName()).append(";\n\n");
    }

    private static boolean hasConstraint(EntityDefinition definition, String flag, String kind) {
        return definition.getFields().stream().anyMatch(field -> {
            boolean textual = FieldTypeResolver.isTextual(field.getJavaType());
            if ("textual".equals(kind)) return field.isRequired() && textual;
            if ("nonTextual".equals(kind)) return field.isRequired() && !textual;
            return false;
        });
    }

    private static String capitalize(String value) {
        if (value == null || value.isEmpty()) return value;
        return value.substring(0, 1).toUpperCase(Locale.ROOT) + value.substring(1);
    }
}
